export const DEFAULT_LANG = 'uz';

/** localStorage'dagi tilni to'g'ridan-to'g'ri o'qiydi (gate'siz). */
export const readStoredLanguage = () => {
  if (typeof window === 'undefined') return DEFAULT_LANG;
  const saved = localStorage.getItem('app_lang');
  return (saved === 'ru' || saved === 'en' || saved === 'uz') ? saved : DEFAULT_LANG;
};

// Hydration muhofazasi.
//
// Ko'p komponentlar `getText('kalit')`ni til argumentisiz chaqiradi, u esa
// tilni localStorage'dan o'qiydi. Server har doim DEFAULT_LANG bilan render
// qiladi, shuning uchun clientdagi BIRINCHI render ham aynan shunday bo'lishi
// shart — aks holda React "hydration failed" xatosini beradi.
// Shu sababli hydration tugamaguncha getLanguage() doim DEFAULT_LANG qaytaradi;
// LanguageProvider mount bo'lgach markHydrated() chaqiriladi va daraxt
// saqlangan til bilan qayta render qilinadi.
let hydrated = false;

export const markHydrated = () => { hydrated = true; };

export const getLanguage = () => {
  if (typeof window === 'undefined' || !hydrated) return DEFAULT_LANG;
  return readStoredLanguage();
};

export const getText = (key, lang = getLanguage()) => {
  return translations[lang]?.[key] ?? translations[DEFAULT_LANG][key] ?? '';
};
